"""Lock the installed runtime dependency closure using PyPI artifact hashes.

Install requirements and constraints into a clean Python 3.12 environment first.
This reads JSON hash metadata instead of downloading wheels for every platform.
"""
from concurrent.futures import ThreadPoolExecutor
import importlib.metadata as metadata
import json
from pathlib import Path
from urllib.request import urlopen

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name


def main():
    root = Path(__file__).resolve().parents[1]
    pending = []
    for line in (root / "requirements.txt").read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            requirement = Requirement(line)
            if requirement.marker is None or requirement.marker.evaluate():
                pending.append(requirement.name)
    selected = {}
    while pending:
        name = canonicalize_name(pending.pop())
        if name in selected:
            continue
        distribution = metadata.distribution(name)
        selected[name] = distribution.version
        for dependency in distribution.requires or []:
            requirement = Requirement(dependency)
            if requirement.marker is None or requirement.marker.evaluate({"extra": ""}):
                pending.append(requirement.name)

    def lock(entry):
        name, version = entry
        with urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
            info = json.load(response)
        hashes = sorted({artifact["digests"]["sha256"] for artifact in info["urls"]
                         if not artifact.get("yanked")})
        if not hashes:
            raise RuntimeError(f"No non-yanked PyPI artifacts for {name}=={version}")
        marker = '; sys_platform == "win32"' if name in {"pywin32", "pyreadline3"} else ""
        return name + "==" + version + marker + " \\\n" + " \\\n".join("    --hash=sha256:" + digest for digest in hashes) + "\n"

    with ThreadPoolExecutor(max_workers=8) as executor:
        entries = list(executor.map(lock, sorted(selected.items())))
    header = "# Generated by tools/lock_runtime.py from the installed Python 3.12 runtime.\n"
    header += "# Includes all non-yanked PyPI artifact hashes for each locked version.\n"
    (root / "requirements.lock").write_text(header + "\n".join(entries), encoding="utf-8")
    print(f"Locked {len(entries)} runtime distributions with SHA-256 hashes")


if __name__ == "__main__":
    main()
